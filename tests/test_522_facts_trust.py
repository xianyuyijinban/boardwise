def _entry(
    tier: str = FACTS_TRUST_VERIFIED,
    *,
    facts: dict | None = None,
    key: str = "ic.ldo.test",
    mpn: str = "RT9013-33GB",
    lcsc: str = "C47773",
    category: str = "ic.ldo",
) -> PartEntry:
    return PartEntry(
        key=key,
        value=mpn,
        mpn=mpn,
        lcsc=lcsc,
        category=category,
        deviceUuid="dev-1",
        libraryUuid="0819f05c4eef4c71ace90d822a990e87",
        facts=dict(facts) if facts is not None else dict(LDO_FACTS),
        facts_trust=tier,
    )


def _ldo_model(vin_net: str = "+5V") -> DesignModel:
    """The 011c model, cut down to the one part these rules need."""
    model = DesignModel()
    model.components["U5"] = Component(
        uid="u5", designator="U5", mpn="RT9013-33GB", lcsc_part="C47773",
        pins=[Pin("1", "VIN", vin_net), Pin("4", "NC", None),
              Pin("5", "VOUT", "VCC")],
    )
    model.nets = {
        vin_net: Net(vin_net, [("U5", "1")]),
        "VCC": Net("VCC", [("U5", "5")]),
    }
    return model


def _states(rule, model) -> dict[str, list]:
    grouped: dict[str, list] = {state: [] for state in OUTCOME_STATES}
    for outcome in rule.outcomes(model):
        grouped[outcome.state].append(outcome)
    return grouped


