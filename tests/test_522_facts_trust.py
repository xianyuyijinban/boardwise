def test_the_three_tiers_are_the_vocabulary_and_each_says_what_it_drives():
    """One name per tier, and a meaning that cannot be added without one.

    The table is what `parts show` prints and `docs/parts.md` documents, so a
    fourth tier would have to arrive with its own row rather than inheriting
    "everything" by default.
    """
    assert FACTS_TRUST_TIERS == (
        FACTS_TRUST_VERIFIED, FACTS_TRUST_MACHINE, FACTS_TRUST_CANDIDATE,
    )
    assert set(FACTS_TRUST_MEANING) == set(FACTS_TRUST_TIERS)
    assert "未人工确认" in FACTS_TRUST_MEANING[FACTS_TRUST_MACHINE]
    assert "不驱动" in FACTS_TRUST_MEANING[FACTS_TRUST_CANDIDATE]


def test_facts_verified_is_a_read_only_alias_that_answers_no_for_machine():
    """**The old code's semantics, held still** (522 §2.1).

    Thirty-odd call sites ask `entry.facts_verified` and mean "did a person sign
    this?". `machine_verified` was not signed, so the alias must answer `False`
    there — the whole reason its findings need a label is that a human has not
    looked. A property rather than a second field, so the two cannot drift.
    """
    verified = _entry(FACTS_TRUST_VERIFIED)
    machine = _entry(FACTS_TRUST_MACHINE)
    candidate = _entry(FACTS_TRUST_CANDIDATE)
    assert verified.facts_verified is True
    assert machine.facts_verified is False
    assert candidate.facts_verified is False
    with pytest.raises(AttributeError):
        machine.facts_verified = True  # type: ignore[misc]


def test_an_invalid_tier_on_a_hand_built_entry_is_refused():
    """The gate on the object, not only in the loader: no fourth value."""
    with pytest.raises(PartError, match="facts_trust must be one of"):
        PartEntry(key="ic.x", lcsc="C1", facts_trust="maybe")


