    entry = _entry(FACTS_TRUST_MACHINE)
    note = machine_trust_note(entry)
    library = PartLibrary(parts=[entry])
    (outcome,) = _states(LdoDropout(library=library), _ldo_model())["OK"]
    assert note in outcome.evidence


