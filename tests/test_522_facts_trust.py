"""522: `facts_verified` becomes three tiers, and the calculation rules use them.

The batch's premise is one sentence: after 521 an accepted fact already has a
**checkable evidence chain** (every quote found verbatim on the page it names,
the pin present in the document, the source a URL or a `file:` path) — but it was
still written as `facts_verified: false`, so no rule read it. 522 splits the
boolean into `candidate` / `machine_verified` / `verified` and gives each tier
its own reach:

| tier | granted by | drives |
|---|---|---|
| `candidate` | `parts fetch`'s regex, `parts add`'s draft | nothing |
| `machine_verified` | `parts hunt --apply-facts` through 521's six gates | current / derating / spacing **calculations**; never a connectivity, safety or isolation conclusion |
| `verified` | a human | everything |

Four properties are asserted here and each of them is the batch's own acceptance
condition rather than a detail:

* the `candidate` gate did **not** loosen (its facts still read None, no rule
  sees them);
* `machine_verified` does **not** move `completion.verdict` to `complete` (an
  unconfirmed fact set is still an open item);
* every finding a `machine_verified` entry drives carries the
  「参数来源：机器核验（…），**未人工确认**」 label, generated by one function;
* `parts hunt --apply-facts` writes `machine_verified`, while `parts fetch` and
  `parts add` without `--verified` still write `candidate`.

Zero network. The hunt leg reuses 521's real page dump under
`E:\\boardwise\\.tmp_cache_hunt520` (520/521's own cache), so no call can be made
and none is.
"""

