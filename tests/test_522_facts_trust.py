def test_verified_is_not_written_and_the_other_two_are():
    """§2.2's write rule, carried over from 039: a value nobody typed is not
    written, so the pre-existing shelf stays byte-identical."""
    verified_body = entry_to_json(_entry(FACTS_TRUST_VERIFIED))
    assert "facts_trust" not in verified_body
    assert "facts_verified" not in verified_body
    for tier in (FACTS_TRUST_MACHINE, FACTS_TRUST_CANDIDATE):
        body = entry_to_json(_entry(tier))
        assert body["facts_trust"] == tier
        assert "facts_verified" not in body


