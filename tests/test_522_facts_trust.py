@pytest.mark.parametrize(
    "body, expected",
    [
        ({"facts_verified": True}, FACTS_TRUST_VERIFIED),
        ({"facts_verified": False}, FACTS_TRUST_CANDIDATE),
        ({}, FACTS_TRUST_VERIFIED),
        ({"facts_trust": "candidate"}, FACTS_TRUST_CANDIDATE),
        ({"facts_trust": "machine_verified"}, FACTS_TRUST_MACHINE),
        ({"facts_trust": "verified"}, FACTS_TRUST_VERIFIED),
        # Both keys, agreeing: the shapes a hand edit or a rewrite leaves behind.
        ({"facts_verified": True, "facts_trust": "verified"}, FACTS_TRUST_VERIFIED),
        (
            {"facts_verified": False, "facts_trust": "candidate"},
            FACTS_TRUST_CANDIDATE,
        ),
    ],
)
def test_the_loader_reads_every_legacy_and_new_spelling(body, expected):
    raw = {"key": "ic.x", "lcsc": "C1", **body}
    if expected != FACTS_TRUST_CANDIDATE:
        raw.update({"deviceUuid": "dev-1", "libraryUuid": "lib-1"})
    assert entry_from_json(raw).facts_trust == expected


