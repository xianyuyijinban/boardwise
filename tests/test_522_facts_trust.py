def test_a_machine_verified_part_stays_on_the_unreviewed_list_with_its_own_class():
    """**An open item, not a closed one** (522 硬要求 2)。

    The shelf holds the facts and 521 checked the evidence, so the row must not
    be sent hunting a datasheet — but nobody signed it, so it must not leave the
    list either. The third bucket is what says so.
    """
    shelf = checkup_engine.shelf_machine_unconfirmed
    entry = _entry(FACTS_TRUST_MACHINE)
    assert shelf(entry) is True
    assert shelf(_entry(FACTS_TRUST_VERIFIED)) is False
    assert checkup_engine.shelf_can_drive_rules(entry) is False
    assert checkup_engine.shelf_can_drive_rules(_entry(FACTS_TRUST_VERIFIED)) is True

    row = {"designator": "U5", "reasons": [UNKNOWN_REASON_MACHINE_UNCONFIRMED]}
    assert unreviewed_classes(row) == [REASON_CLASS_MACHINE_UNCONFIRMED]
    counts = unreviewed_counts_by_class([row])
    assert counts == {REASON_CLASS_MACHINE_UNCONFIRMED: 1}


def test_the_three_tier_counts_are_read_from_the_rows_the_report_carries():
    rows = [
        {"factsTrust": FACTS_TRUST_VERIFIED},
        {"factsTrust": FACTS_TRUST_MACHINE},
        {"factsTrust": FACTS_TRUST_MACHINE},
        {"factsTrust": FACTS_TRUST_CANDIDATE},
        {"factsTrust": ""},   # a part on no shelf: not a tier
        "not-a-row",
    ]
    assert facts_trust_counts(rows) == {
        "verified": 1, "machineVerified": 2, "candidate": 1,
    }
    assert facts_trust_counts(None) == {
        "verified": 0, "machineVerified": 0, "candidate": 0,
    }


def test_the_machine_tier_does_not_push_the_verdict_to_complete():
    """**522 硬要求 2, stated as the arithmetic it is.**

    A report with a machine-verified part still counts an unreviewed part, so the
    verdict stays `incomplete`; and even when nothing else is owed, the part is
    still an open item rather than a closed one. Either way a machine's reading
    must never produce `complete` on its own.
    """
    from boardwise.cli import _completion_body

    unreviewed = [{
        "designator": "U5",
        "reasons": [UNKNOWN_REASON_MACHINE_UNCONFIRMED],
        "factsTrust": FACTS_TRUST_MACHINE,
        "factsVerified": False,
    }]
    body = _completion_body(
        scope={"rules": 1, "boards": 1, "pages": 1},
        summary={"errorCount": 0, "errors": []},
        unreviewed=unreviewed,
        triage=[],
        architecture={"totals": {"slots": 1, "filled": 1, "stale": 0}},
        judged_rows=[],
    )
    assert body["verdict"] == "incomplete", (
        "an unconfirmed fact set is an open item; `complete` would be the green "
        "light 522 §5.4 forbids"
    )
    assert body["factsTrust"]["machineVerified"] == 1
    assert body["unreviewedByClass"] == {REASON_CLASS_MACHINE_UNCONFIRMED: 1}
    assert any("未审" in reason for reason in body["verdictWhy"])


