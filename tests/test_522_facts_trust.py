def _u2_board() -> DesignModel:
    return DesignModel(components={
        "U2": Component(
            uid="u2", designator="U2", lcsc_part="C601651", mpn="UCC21520DWR",
        ),
    })


@pytest.mark.skipif(
    not (REAL_CACHE / "C601651" / "C601651.txt").is_file(),
    reason="520/521's real page dump is not on this machine",
)
def test_apply_facts_writes_machine_verified_not_candidate(tmp_path, monkeypatch):
    """§4's first row: the six gates passed, so the tier is `machine_verified`.

    Offline throughout — the same seams 521's own end-to-end test refuses calls
    on, so an outbound attempt would be a test failure rather than a slow run.
    """
    shelf = tmp_path / "parts.json"
    save_parts(PartLibrary(parts=[]), shelf)
    answers = tmp_path / "answers.json"
    answers.write_text(json.dumps(REAL_ANSWERS, ensure_ascii=False), encoding="utf-8")

    monkeypatch.setattr(cli, "_load_model", lambda *a, **k: (_u2_board(), None))

    def refuse(*_a, **_k):  # pragma: no cover - a call here is the failure
        raise AssertionError("--apply-facts must not touch the network")

    monkeypatch.setattr(cli, "_fetch_url", refuse)
    monkeypatch.setattr(cli, "urllib_product_fetcher", refuse, raising=False)
    monkeypatch.setattr(cli, "_pdf_text", refuse)

    code = cli.main([
        "parts", "hunt",
        "--file", str(tmp_path / "board.epro2"),
        "--out", str(tmp_path / "out"),
        "--offline",
        "--cache", str(REAL_CACHE),
        "--apply-facts", str(answers),
        "--shelf", str(shelf),
    ])
    assert code == 0

    library = load_parts(shelf)
    (entry,) = library.parts
    assert entry.facts_trust == FACTS_TRUST_MACHINE
    assert entry.facts_verified is False, "no human has signed it"
    assert entry.facts is not None, "the calculation rules have to read it"
    # Round-tripping the file keeps the tier (the writer spells it out).
    raw = json.loads(shelf.read_text(encoding="utf-8"))["parts"][0]
    assert raw["facts_trust"] == FACTS_TRUST_MACHINE
    assert "facts_verified" not in raw
    assert entry.provenance.kind == "hunt-read"


